    }

    private static IEnumerable<string> BuildWarnings(IReadOnlyList<ScenarioStep> steps)
    {
        if (steps.Any(static step => string.Equals(step.Action, "tapPoint", StringComparison.OrdinalIgnoreCase)))
        {
            yield return "Draft includes coordinate taps; add scenario metadata for device layout before using in CI.";
        }

        if (steps.All(static step =>
            !string.Equals(step.Action, "waitVisible", StringComparison.OrdinalIgnoreCase) &&
            !string.Equals(step.Action, "waitElement", StringComparison.OrdinalIgnoreCase)))
        {
            yield return "Draft has no waitVisible or waitElement steps; add waits around asynchronous UI transitions.";
        }
    }

    private static IEnumerable<ReplayScenarioDraftSuggestion> BuildSuggestions(IReadOnlyList<ScenarioStep> steps)
    {
        for (var i = 0; i < steps.Count; i++)
        {
            var step = steps[i];
            if (string.Equals(step.Action, "tapText", StringComparison.OrdinalIgnoreCase) &&
                !HasMatchingPreviousWait(steps, i))
            {
                yield return new ReplayScenarioDraftSuggestion(i + 1, "selector", "medium", "Review whether this tap should be preceded by waitVisible for the same text.");
            }
            else if (string.Equals(step.Action, "tapElement", StringComparison.OrdinalIgnoreCase) &&
                !HasMatchingPreviousWait(steps, i))
            {
                yield return new ReplayScenarioDraftSuggestion(i + 1, "selector", "medium", "Review whether this tap should be preceded by waitElement for the same selector.");
            }
            else if (string.Equals(step.Action, "tapPoint", StringComparison.OrdinalIgnoreCase))
            {
                yield return new ReplayScenarioDraftSuggestion(i + 1, "coordinate", "low", "Replace coordinate tap with tapText or add layout metadata if possible.");
            }
            else if (string.Equals(step.Action, "takeScreenshot", StringComparison.OrdinalIgnoreCase))
            {
                yield return new ReplayScenarioDraftSuggestion(i + 1, "visual", "medium", "Consider upgrading screenshot capture to assertScreenshot with a baseline or region hash.");
            }
            else if (string.Equals(step.Action, "waitStep", StringComparison.OrdinalIgnoreCase) ||
                string.Equals(step.Action, "waitActionReady", StringComparison.OrdinalIgnoreCase) ||
                string.Equals(step.Action, "assertEvent", StringComparison.OrdinalIgnoreCase))
            {
                yield return new ReplayScenarioDraftSuggestion(i + 1, "telemetry", "medium", "Verify this semantic telemetry assertion is emitted reliably by the app before using it as a CI gate.");
            }
        }
    }

    private static bool HasMatchingPreviousWait(IReadOnlyList<ScenarioStep> steps, int index)
    {
        if (index <= 0)
        {
            return false;
        }

        var wait = CreatePreTapWaitStep(steps[index]);
        return wait is not null &&
            string.Equals(GetWaitKey(steps[index - 1]), GetWaitKey(wait), StringComparison.OrdinalIgnoreCase);
    }

    private static IEnumerable<ReplayScenarioDraftReviewItem> BuildReviewItems(
        IReadOnlyList<string> warnings,
        IReadOnlyList<ReplayScenarioDraftSuggestion> suggestions,
        IReadOnlyList<ReplayScenarioDraftStepOrigin> origins,
        IReadOnlyList<ReplayScenarioDraftNormalization> normalizations)
    {
        foreach (var warning in warnings)
        {
            yield return new ReplayScenarioDraftReviewItem(
                "warning",
                "scenario",
                null,
                warning,
                "luotsi scenario-validate --file <scenario.json>");
        }

        foreach (var suggestion in suggestions)
        {
            var severity = string.Equals(suggestion.Confidence, "low", StringComparison.OrdinalIgnoreCase)
                ? "warning"
                : "info";
            yield return new ReplayScenarioDraftReviewItem(
                severity,
                suggestion.Kind,
                suggestion.StepIndex,
                suggestion.Message,
                BuildReviewCommand(suggestion.Kind));
        }

        foreach (var origin in origins.Where(static origin => string.Equals(origin.Confidence, "low", StringComparison.OrdinalIgnoreCase)))
        {
            yield return new ReplayScenarioDraftReviewItem(
                "warning",
                "provenance",
                origin.StepIndex,
                $"Low-confidence generated step from {origin.Source}; review against the source timeline before committing.",
                origin.SourceCommand ?? "luotsi replay timeline --artifacts <artifact-root> --context 3");
        }

        foreach (var origin in origins.Where(static origin => origin.Detail?.Contains("selector:", StringComparison.OrdinalIgnoreCase) is true))
        {
            yield return new ReplayScenarioDraftReviewItem(
                "info",
                "selector",
                origin.StepIndex,
                "Inspect selector metadata was captured in the replay origin. Generated scenario steps can now replay structured element selectors; verify resource_id/class/region constraints before committing.",
                origin.SourceCommand);
        }

        foreach (var normalization in normalizations)
        {
            yield return new ReplayScenarioDraftReviewItem(
                "info",
                "normalization",
                null,
                normalization.Detail,
                normalization.SourceCommand);
        }
    }

    private static string? BuildSourceCommand(string? sourcePath, int? sequence)
    {
        if (string.IsNullOrWhiteSpace(sourcePath) || sequence is null)
        {
            return null;
        }

        return $"luotsi replay timeline --artifacts <artifact-root> --source-path {Quote(sourcePath)} --sequence {sequence.Value} --context 2";
    }

    private static string Quote(string value) =>
        value.Contains(' ', StringComparison.Ordinal) ? "\"" + value.Replace("\"", "\\\"", StringComparison.Ordinal) + "\"" : value;

    private static string BuildValidateCommand(string output) =>
        $"luotsi scenario-validate --file {Quote(output)}";

    private static ReplayScenarioDraftRunHandoff? BuildRunHandoff(string? output, ReplayScenarioDraftValidation? validation, ScenarioFile scenario)
    {
        if (string.IsNullOrWhiteSpace(output))
        {
            return null;
        }

        if (validation is null)
        {
            return new ReplayScenarioDraftRunHandoff(
                "needs_validation",
                "Validate the generated scenario before planning or running it.");
        }

        if (!string.Equals(validation.Status, "validated", StringComparison.OrdinalIgnoreCase))
        {
            return new ReplayScenarioDraftRunHandoff(
                "blocked",
                "Resolve static validation errors before planning or running the generated scenario.");
        }

        var package = ResolvePreflightPackage(scenario);
        var serial = scenario.Metadata?.Device?.Serial;
        return new ReplayScenarioDraftRunHandoff(
            "ready",
            "Static validation passed; plan the generated scenario before running it on a selected device.",
            BuildPreflightCommand(package, serial),
            BuildDryRunCommand(output),
            BuildRunCommand(output, package, serial),
            BuildClaimedRunCommand(output, package, serial));
    }

    private static string? ResolvePreflightPackage(ScenarioFile scenario)
    {
        if (!string.IsNullOrWhiteSpace(scenario.Metadata?.Package))
        {
            return scenario.Metadata.Package;
        }

        return EnumerateScenarioSteps(scenario)
            .Where(step => !string.IsNullOrWhiteSpace(step.Package))
            .Select(step => step.Package)
            .FirstOrDefault();
    }

    private static IEnumerable<ScenarioStep> EnumerateScenarioSteps(ScenarioFile scenario)
    {
        foreach (var step in scenario.Setup ?? [])
        {
            yield return step;
        }

        foreach (var step in scenario.Steps)
        {
            yield return step;
        }

        foreach (var step in scenario.Teardown ?? [])
        {
            yield return step;
        }
    }

    private static string BuildPreflightCommand(string? package, string? serial)
    {
        var device = string.IsNullOrWhiteSpace(serial) ? "<serial>" : Quote(serial);
        return string.IsNullOrWhiteSpace(package)
            ? $"luotsi preflight --device {device} --package <app.id>"
            : $"luotsi preflight --device {device} --package {Quote(package)}";
    }

    private static string BuildDryRunCommand(string output) =>
        $"luotsi run --path {Quote(output)} --dry-run";

    private static string BuildRunCommand(string output, string? package, string? serial)
    {
        var device = string.IsNullOrWhiteSpace(serial) ? "<serial>" : Quote(serial);
        var command = $"luotsi run --file {Quote(output)} --device {device}";
        return string.IsNullOrWhiteSpace(package)
            ? command
            : command + $" --package {Quote(package)}";
    }

    private static string? BuildClaimedRunCommand(string output, string? package, string? serial)
    {
        if (string.IsNullOrWhiteSpace(package) || string.IsNullOrWhiteSpace(serial))
        {
            return null;
        }

        return $"luotsi run --file {Quote(output)} --device {Quote(serial)} --package {Quote(package)} --claim-device --claim-wait-sec 60";
    }

    private static string? BuildReviewCommand(string kind) =>
        kind switch
        {
            "selector" => "luotsi screen-state",
            "coordinate" => "luotsi scenario-validate --file <scenario.json>",
            "visual" => "luotsi replay open --artifacts <artifact-root>",
            "telemetry" => "luotsi telemetry-tail",
            _ => null
        };

    private static bool TryGetString(JsonElement root, string name, out string value)
    {
        value = string.Empty;
        if (root.ValueKind != JsonValueKind.Object ||
            !root.TryGetProperty(name, out var property) ||
            property.ValueKind != JsonValueKind.String ||
            string.IsNullOrWhiteSpace(property.GetString()))
        {
            return false;
        }

        value = property.GetString()!;
        return true;
    }

    private static string? TryGetOptionalString(JsonElement root, string name) =>
        TryGetString(root, name, out var value) ? value : null;

    private static bool TryGetSelectorText(JsonElement evt, out string text)
    {
        text = string.Empty;
        if (!TryCreateSelector(evt, out var selector) || string.IsNullOrWhiteSpace(selector.Text))
        {
            return false;
        }

        text = selector.Text;
        return true;
    }

    private static bool TryCreateSelector(JsonElement evt, out ScreenElementSelector selector)
    {
        selector = new ScreenElementSelector();
        if (evt.ValueKind != JsonValueKind.Object ||
            !evt.TryGetProperty("selector", out var source) ||
            source.ValueKind != JsonValueKind.Object)
        {
            return false;
        }

        var candidate = new ScreenElementSelector(
            TryGetOptionalString(source, "text"),
            TryGetOptionalString(source, "text_match", "textMatch") ?? ScreenElementMatchModes.Contains,
            TryGetOptionalString(source, "content_description", "contentDescription"),
            TryGetOptionalString(source, "content_description_match", "contentDescriptionMatch") ?? ScreenElementMatchModes.Exact,
            TryGetOptionalString(source, "resource_id", "resourceId"),
            TryGetOptionalString(source, "resource_id_match", "resourceIdMatch") ?? ScreenElementMatchModes.Exact,
            TryGetOptionalString(source, "class_name", "className"),
            TryGetOptionalString(source, "class_name_match", "classNameMatch") ?? ScreenElementMatchModes.Exact,
            TryGetSelectorRegion(source),
            TryGetBool(source, "allow_ambiguous", "allowAmbiguous") ?? false);

        if (!candidate.HasCriteria)
        {
            return false;
        }

        selector = ScreenElementSelectorValidator.Validate(candidate, "selector");
        return true;
    }

    private static Bounds? TryGetSelectorRegion(JsonElement selector)
    {
        if (!selector.TryGetProperty("region", out var region) ||
            region.ValueKind != JsonValueKind.Object ||
            !TryGetInt32(region, "left", out var left) ||
            !TryGetInt32(region, "top", out var top) ||
            !TryGetInt32(region, "right", out var right) ||
            !TryGetInt32(region, "bottom", out var bottom))
        {
            return null;
        }

        return new Bounds(left, top, right, bottom);
    }

    private static string? TryGetOptionalString(JsonElement root, params string[] names)
        => names
            .Select(name => TryGetString(root, name, out var value) ? value : null)
            .FirstOrDefault(static value => value is not null);

    private static bool? TryGetBool(JsonElement root, params string[] names)
        => names
            .Select(name => TryGetBool(root, name))
            .FirstOrDefault(static value => value is not null);

    private static string CreateInspectCommandDetail(JsonElement evt, string command) =>
        TryFormatSelector(evt, out var selector)
            ? $"{command} selector: {selector}"
            : command;

    private static bool TryFormatSelector(JsonElement evt, out string detail)
    {
        detail = string.Empty;
        if (evt.ValueKind != JsonValueKind.Object ||
            !evt.TryGetProperty("selector", out var selector) ||
            selector.ValueKind != JsonValueKind.Object)
        {
            return false;
        }

        var parts = new List<string>();
        AddSelectorPart(parts, selector, "text", "text_match", ScreenElementMatchModes.Contains);
        AddSelectorPart(parts, selector, "content_description", "content_description_match", ScreenElementMatchModes.Exact);
        AddSelectorPart(parts, selector, "resource_id", "resource_id_match", ScreenElementMatchModes.Exact);
        AddSelectorPart(parts, selector, "class_name", "class_name_match", ScreenElementMatchModes.Exact);
        if (selector.TryGetProperty("region", out var region) &&
            region.ValueKind == JsonValueKind.Object &&
            TryGetInt32(region, "left", out var left) &&
            TryGetInt32(region, "top", out var top) &&
            TryGetInt32(region, "right", out var right) &&
            TryGetInt32(region, "bottom", out var bottom))
        {
            parts.Add($"region={left},{top},{right},{bottom}");
        }

        if (TryGetBool(selector, "allow_ambiguous") is true)
        {
            parts.Add("allow_ambiguous=true");
        }

        detail = string.Join(", ", parts);
        return parts.Count > 0;
    }

    private static void AddSelectorPart(List<string> parts, JsonElement selector, string valueName, string matchName, string defaultMatch)
    {
        if (!TryGetString(selector, valueName, out var value))
        {
            return;
        }

        var match = TryGetOptionalString(selector, matchName) ?? defaultMatch;
        parts.Add($"{valueName}:{match}={value}");
    }

    private static string? LastResourceSegment(string? value)
    {
        if (string.IsNullOrWhiteSpace(value))
        {
            return null;
        }

        var index = value.LastIndexOf('/');
        return index >= 0 && index + 1 < value.Length ? value[(index + 1)..] : value;
    }

    private static string? FirstNonBlank(params string?[] values) =>
        values.FirstOrDefault(static value => !string.IsNullOrWhiteSpace(value));

    private static int? TryGetOptionalInt32(JsonElement root, string name) =>
        TryGetInt32(root, name, out var value) ? value : null;

    private static bool TryGetInt32(JsonElement root, string name, out int value)
    {
        value = 0;
        return root.ValueKind == JsonValueKind.Object &&
            root.TryGetProperty(name, out var property) &&
            property.ValueKind == JsonValueKind.Number &&
            property.TryGetInt32(out value);
    }

    private static bool? TryGetBool(JsonElement root, string name)
    {
        if (root.ValueKind != JsonValueKind.Object ||
            !root.TryGetProperty(name, out var property) ||
            property.ValueKind is not JsonValueKind.True and not JsonValueKind.False)
        {
            return null;
        }

        return property.GetBoolean();
    }

    private static DateTimeOffset? TryReadTimestamp(JsonElement root)
    {
        return new[] { "occurred_at", "occurredAt", "started_at", "startedAt", "ended_at", "endedAt" }
            .Select(name =>
                TryGetString(root, name, out var value) &&
                DateTimeOffset.TryParse(value, System.Globalization.CultureInfo.InvariantCulture, System.Globalization.DateTimeStyles.RoundtripKind, out var timestamp)
                    ? (DateTimeOffset?)timestamp
                    : null)
            .FirstOrDefault(timestamp => timestamp.HasValue);
    }

