    private static ReplayScenarioDraftPackageProvenance? InferPackageProvenance(IReadOnlyList<DraftTimelineEvent> events)
    {
        foreach (var timelineEvent in events)
        {
            var evt = timelineEvent.Element;
            if (TryFindPackageCandidate(evt, string.Empty, out var package, out var source))
            {
                TryGetString(evt, "type", out var eventType);
                TryGetString(evt, "command", out var command);
                return new ReplayScenarioDraftPackageProvenance(
                    package,
                    source,
                    string.IsNullOrWhiteSpace(eventType) ? "timeline_event" : eventType,
                    string.IsNullOrWhiteSpace(command) ? null : command,
                    timelineEvent.SourcePath,
                    timelineEvent.Sequence,
                    timelineEvent.Timestamp,
                    BuildSourceCommand(timelineEvent.SourcePath, timelineEvent.Sequence));
            }
        }

        return null;
    }

    private ReplayScenarioDraftDeviceProvenance? InferDeviceProvenance(string artifactRoot)
    {
        var files = _fileSystem.GetFiles(artifactRoot, SessionReplayArtifacts.MetadataFileName, SearchOption.AllDirectories);
        var candidates = files
            .Order(StringComparer.OrdinalIgnoreCase)
            .Select(file => TryReadDeviceProvenance(artifactRoot, file))
            .Where(static candidate => candidate is not null)
            .Select(static candidate => candidate!)
            .ToArray();

        return candidates
            .Select(static candidate => candidate.Serial)
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .Take(2)
            .Count() == 1
                ? candidates[0]
                : null;
    }

    private ReplayScenarioDraftDeviceProvenance? TryReadDeviceProvenance(string artifactRoot, string file)
    {
        try
        {
            using var stream = _fileSystem.OpenRead(file);
            using var document = JsonDocument.Parse(stream);
            var root = document.RootElement;
            if (root.ValueKind != JsonValueKind.Object ||
                !TryGetString(root, "schema", out var schema) ||
                !string.Equals(schema, ResultSchemas.SessionReplay, StringComparison.Ordinal) ||
                !TryGetString(root, "target", out var target) ||
                !IsLikelyAdbSerial(target))
            {
                return null;
            }

            return new ReplayScenarioDraftDeviceProvenance(
                target.Trim(),
                "session_replay.target",
                TryGetString(root, "sessionKind", out var sessionKind) ? sessionKind : "replay",
                TryGetString(root, "sessionId", out var sessionId) ? sessionId : null,
                Path.GetRelativePath(artifactRoot, file).Replace('\\', '/'),
                TryReadTimestamp(root));
        }
        catch (Exception ex) when (ex is IOException or UnauthorizedAccessException or JsonException or FormatException)
        {
            return null;
        }
    }

    private static bool TryFindPackageCandidate(JsonElement root, string source, out string package, out string packageSource)
    {
        package = string.Empty;
        packageSource = string.Empty;
        if (root.ValueKind != JsonValueKind.Object)
        {
            return false;
        }

        var packageCandidate = PackagePropertyNames
            .Select(name => (Name: name, Value: TryGetString(root, name, out var value) ? value : null))
            .Where(candidate => candidate.Value is not null && IsLikelyAndroidPackage(candidate.Value))
            .FirstOrDefault();
        if (packageCandidate.Value is not null)
        {
            package = packageCandidate.Value.Trim();
            packageSource = BuildPackageSource(source, packageCandidate.Name);
            return true;
        }

        var focusCandidate = FocusPropertyNames
            .Select(name =>
            {
                var focusedPackage = string.Empty;
                var found = TryGetString(root, name, out var focus) &&
                    TryParsePackageFromFocus(focus, out focusedPackage);
                return (Name: name, Package: found ? focusedPackage : null);
            })
            .Where(candidate => candidate.Package is not null)
            .FirstOrDefault();
        if (focusCandidate.Package is not null)
        {
            package = focusCandidate.Package;
            packageSource = BuildPackageSource(source, focusCandidate.Name);
            return true;
        }

        var nestedPackageCarrierProperties = root.EnumerateObject()
            .Where(property => property.Value.ValueKind == JsonValueKind.Object &&
                PackageCarrierPropertyNames.Contains(property.Name, StringComparer.Ordinal));
        var nestedPackageCandidate = nestedPackageCarrierProperties
            .Select(property =>
            {
                var nestedPackage = string.Empty;
                var nestedPackageSource = string.Empty;
                var found = TryFindPackageCandidate(
                    property.Value,
                    BuildPackageSource(source, property.Name),
                    out nestedPackage,
                    out nestedPackageSource);
                return (Found: found, Package: nestedPackage, PackageSource: nestedPackageSource);
            })
            .Where(candidate => candidate.Found)
            .FirstOrDefault();
        if (nestedPackageCandidate.Found)
        {
            package = nestedPackageCandidate.Package;
            packageSource = nestedPackageCandidate.PackageSource;
            return true;
        }

        return false;
    }

    private static string BuildPackageSource(string source, string propertyName) =>
        string.IsNullOrWhiteSpace(source) ? propertyName : source + "." + propertyName;

    private static bool TryParsePackageFromFocus(string value, out string package)
    {
        package = string.Empty;
        var slash = value.IndexOf('/', StringComparison.Ordinal);
        if (slash <= 0)
        {
            return false;
        }

        var start = slash - 1;
        while (start >= 0 && !char.IsWhiteSpace(value[start]) && value[start] is not '{' and not '}')
        {
            start--;
        }

        var candidate = value[(start + 1)..slash];
        var colon = candidate.LastIndexOf(':');
        if (colon >= 0 && colon + 1 < candidate.Length)
        {
            candidate = candidate[(colon + 1)..];
        }

        if (!IsLikelyAndroidPackage(candidate))
        {
            return false;
        }

        package = candidate.Trim();
        return true;
    }

    private static bool IsLikelyAndroidPackage(string value)
    {
        var candidate = value.Trim();
        return !string.IsNullOrWhiteSpace(candidate) &&
            candidate.Contains(".", StringComparison.Ordinal) &&
            !candidate.StartsWith(".", StringComparison.Ordinal) &&
            !candidate.EndsWith(".", StringComparison.Ordinal) &&
            !candidate.Contains("..", StringComparison.Ordinal) &&
            !candidate.Contains("/", StringComparison.Ordinal) &&
            !candidate.Contains("\\", StringComparison.Ordinal) &&
            !candidate.Contains("<", StringComparison.Ordinal) &&
            !candidate.Contains(">", StringComparison.Ordinal) &&
            !candidate.Contains("{", StringComparison.Ordinal) &&
            !candidate.Contains("}", StringComparison.Ordinal) &&
            !candidate.Contains("$", StringComparison.Ordinal) &&
            !candidate.Contains(":", StringComparison.Ordinal) &&
            !candidate.EndsWith(".apk", StringComparison.OrdinalIgnoreCase) &&
            candidate.Any(static ch => char.IsLetter(ch)) &&
            candidate.All(static ch => char.IsLetterOrDigit(ch) || ch is '_' or '.') &&
            candidate.Split('.', StringSplitOptions.RemoveEmptyEntries).Length >= 2;
    }

    private static bool IsLikelyAdbSerial(string value)
    {
        var candidate = value.Trim();
        if (string.IsNullOrWhiteSpace(candidate) ||
            candidate.Length < 3 ||
            candidate.Any(char.IsWhiteSpace) ||
            candidate.Contains("<", StringComparison.Ordinal) ||
            candidate.Contains(">", StringComparison.Ordinal) ||
            candidate.Contains("{", StringComparison.Ordinal) ||
            candidate.Contains("}", StringComparison.Ordinal) ||
            candidate.Contains("$", StringComparison.Ordinal) ||
            candidate.Contains("/", StringComparison.Ordinal) ||
            candidate.Contains("\\", StringComparison.Ordinal))
        {
            return false;
        }

        var colon = candidate.LastIndexOf(':');
        if (colon >= 0)
        {
            var host = candidate[..colon];
            var port = candidate[(colon + 1)..];
            return !string.IsNullOrWhiteSpace(host) &&
                port.Length > 0 &&
                port.All(char.IsDigit) &&
                host.All(static ch => char.IsLetterOrDigit(ch) || ch is '.' or '_' or '-');
        }

        if (candidate.Contains(".", StringComparison.Ordinal))
        {
            return false;
        }

        return candidate.Any(char.IsLetterOrDigit) &&
            candidate.All(static ch => char.IsLetterOrDigit(ch) || ch is '_' or '-');
    }

    private IReadOnlyList<DraftTimelineEvent> ReadTimelineEvents(string artifactRoot)
    {
        var files = _fileSystem.GetFiles(artifactRoot, SessionReplayArtifacts.TimelineFileName, SearchOption.AllDirectories);
        if (files.Count == 0)
        {
            throw new UsageException($"No {SessionReplayArtifacts.TimelineFileName} was found under artifact root '{artifactRoot}'.");
        }

        return files.Order(StringComparer.OrdinalIgnoreCase)
            .SelectMany(file => ReadTimelineEventsFromFile(artifactRoot, file))
            .ToArray();
    }

    private IEnumerable<DraftTimelineEvent> ReadTimelineEventsFromFile(string artifactRoot, string file)
    {
        using var stream = _fileSystem.OpenRead(file);
        using var reader = new StreamReader(stream, Encoding.UTF8, detectEncodingFromByteOrderMarks: true, bufferSize: 4096);
        var sequence = 0;
        while (reader.ReadLine() is { } line)
        {
            if (string.IsNullOrWhiteSpace(line))
            {
                continue;
            }

            var evt = ParseTimelineEvent(file, line);
            if (evt is not null)
            {
                yield return new DraftTimelineEvent(
                    Path.GetRelativePath(artifactRoot, file).Replace('\\', '/'),
                    sequence,
                    TryReadTimestamp(evt.Value),
                    evt.Value);
            }

            sequence++;
        }
    }

    private static JsonElement? ParseTimelineEvent(string file, string line)
    {
        try
        {
            using var document = JsonDocument.Parse(line);
            return document.RootElement.ValueKind == JsonValueKind.Object
                ? document.RootElement.Clone()
                : null;
        }
        catch (JsonException ex)
        {
            throw new UsageException($"replay scenario-draft encountered invalid JSON in '{file}'. {ex.Message} Line: {line}");
        }
    }

    private static IReadOnlyList<DraftStep> CreateSteps(IReadOnlyList<DraftTimelineEvent> events)
    {
        var steps = new List<DraftStep>();
        foreach (var timelineEvent in events)
        {
            var evt = timelineEvent.Element;
            if (!TryGetString(evt, "type", out var type))
            {
                continue;
            }

            if (string.Equals(type, "command_result", StringComparison.Ordinal))
            {
                steps.AddRange(CreateInspectCommandSteps(evt).Select(timelineEvent.Attach));
                continue;
            }

            if (string.Equals(type, "screen_delta", StringComparison.Ordinal))
            {
                steps.AddRange(CreateScreenDeltaSteps(evt).Select(timelineEvent.Attach));
                continue;
            }

            var step = type switch
            {
                "scenario_step_passed" or "scenario_step_continued_on_error" or "scenario_step_failed" => CreateScenarioStep(evt, type),
                "view_screenshot_captured" => CreateScreenshotStep(evt, type),
                "view_key_command_sent" => CreateKeyCommandStep(evt, type),
                _ => null
            };

            if (step is not null)
            {
                steps.Add(timelineEvent.Attach(step));
            }
        }

        return steps;
    }

    private static IReadOnlyList<DraftStep> CreateScreenDeltaSteps(JsonElement evt)
    {
        if (!evt.TryGetProperty("delta", out var delta) ||
            delta.ValueKind != JsonValueKind.Object ||
            !delta.TryGetProperty("added", out var added) ||
            added.ValueKind != JsonValueKind.Array)
        {
            return [];
        }

        var steps = new List<DraftStep>();
        var seen = new HashSet<string>(StringComparer.OrdinalIgnoreCase);
        foreach (var element in added.EnumerateArray())
        {
            var text = TryGetOptionalString(element, "text") ?? TryGetOptionalString(element, "content_description");
            if (string.IsNullOrWhiteSpace(text) || !seen.Add(text))
            {
                continue;
            }

            steps.Add(new DraftStep(
                new ScenarioStep("wait visible " + text, "waitVisible", text, null, null, TimeoutSec: 15),
                "screen_delta",
                "screen_delta",
                null,
                "added text: " + text,
                "medium"));
            if (steps.Count == 3)
            {
                break;
            }
        }

        return steps;
    }

    private static IReadOnlyList<DraftStep> CreateInspectCommandSteps(JsonElement evt)
    {
        if (!TryGetString(evt, "command", out var command) || TryGetBool(evt, "ok") is false)
        {
            return [];
        }

        var data = evt.TryGetProperty("data", out var dataElement) && dataElement.ValueKind == JsonValueKind.Object
            ? dataElement
            : default;
        if (command is "telemetry_tail" or "telemetry_watch")
        {
            return CreateTelemetrySteps(data);
        }

        var step = command switch
        {
            "tap_text" or "tap_element" or "tap_selector" => CreateSelectorOrTextStep(evt, data, "tapElement", "tapText", "tap element", "tap text"),
            "tap_point" => CreateTapPointStep(data),
            "wait_visible" or "wait_element" or "wait_selector" => CreateSelectorOrTextStep(evt, data, "waitElement", "waitVisible", "wait element", "wait visible"),
            "type_text" => CreateTextStep(evt, data, "typeText", "type text"),
            "keyevent" => TryGetString(data, "code", out var code)
                ? new ScenarioStep("keyevent " + code, "keyevent", null, code, null)
                : null,
            "screenshot" or "take_screenshot" => CreateLabelStep(data, "takeScreenshot", "screenshot"),
            _ => null
        };

        return step is null ? [] : [new DraftStep(step, "inspect_command", "command_result", command, CreateInspectCommandDetail(evt, command), "medium")];
    }

    private static ScenarioStep? CreateTapPointStep(JsonElement data)
    {
        if (!TryGetInt32(data, "x", out var x) || !TryGetInt32(data, "y", out var y))
        {
            return null;
        }

        var label = TryGetOptionalString(data, "label") ?? "replay-tap-point";
        return new ScenarioStep(
            "tap point " + label,
            "tapPoint",
            null,
            null,
            null,
            Label: label,
            X: x,
            Y: y,
            PostTapDelayMs: TryGetOptionalInt32(data, "post_tap_delay_ms") ?? TryGetOptionalInt32(data, "postTapDelayMs"));
    }

    private static IReadOnlyList<DraftStep> CreateTelemetrySteps(JsonElement data)
    {
        if (data.ValueKind != JsonValueKind.Object)
        {
            return [];
        }

        var steps = new List<DraftStep>();
        if (data.TryGetProperty("events", out var events) && events.ValueKind == JsonValueKind.Array)
        {
            steps.AddRange(events.EnumerateArray()
                .Select(CreateTelemetryStep)
                .OfType<ScenarioStep>()
                .Select(static step => new DraftStep(step, "telemetry", "command_result", "telemetry", step.Event ?? step.Step ?? step.Text, "medium")));
        }
        else
        {
            var step = CreateTelemetryStep(data);
            if (step is not null)
            {
                steps.Add(new DraftStep(step, "telemetry", "command_result", "telemetry", step.Event ?? step.Step ?? step.Text, "medium"));
            }
        }

        return steps;
    }

    private static ScenarioStep? CreateTelemetryStep(JsonElement telemetryEvent)
    {
        if (!TryGetString(telemetryEvent, "event", out var eventName))
        {
            return null;
        }

        if (string.Equals(eventName, "step", StringComparison.OrdinalIgnoreCase) &&
            TryGetString(telemetryEvent, "step", out var stepName))
        {
            return new ScenarioStep("wait step " + stepName, "waitStep", null, null, stepName, TimeoutSec: 15);
        }

        if (string.Equals(eventName, "action_ready", StringComparison.OrdinalIgnoreCase) &&
            TryGetString(telemetryEvent, "action", out var actionName))
        {
            TryGetString(telemetryEvent, "step", out var telemetryStepName);
            return new ScenarioStep("wait action " + actionName, "waitActionReady", actionName, null, string.IsNullOrWhiteSpace(telemetryStepName) ? null : telemetryStepName, TimeoutSec: 15);
        }

        return new ScenarioStep("assert event " + eventName, "assertEvent", null, null, null, Event: eventName, TimeoutSec: 15);
    }

    private static DraftStep? CreateScenarioStep(JsonElement evt, string eventType)
    {
        if (!TryGetString(evt, "action", out var action))
        {
            return null;
        }

        TryGetString(evt, "step", out var name);
        var stepName = name ?? action;
        return action switch
        {
            "waitVisible" or "waitNotVisible" or "tapText" or "typeText" or "waitLog" => TryGetString(evt, "text", out var text)
                ? new DraftStep(new ScenarioStep(stepName, action, text, null, null, TimeoutSec: action.StartsWith("wait", StringComparison.OrdinalIgnoreCase) ? 15 : null), "scenario_event", eventType, null, action + ": " + text, "high")
                : null,
            "waitElement" or "tapElement" => TryCreateSelector(evt, out var selector)
                ? new DraftStep(new ScenarioStep(stepName, action, null, null, null, TimeoutSec: action.StartsWith("wait", StringComparison.OrdinalIgnoreCase) ? 15 : null, Selector: selector), "scenario_event", eventType, null, action + ": " + selector.Describe(), "high")
                : null,
            "keyevent" => TryGetString(evt, "code", out var code)
                ? new DraftStep(new ScenarioStep(stepName, action, null, code, null), "scenario_event", eventType, null, "keyevent: " + code, "high")
                : null,
            "waitStep" => TryGetString(evt, "step", out var waitStep)
                ? new DraftStep(new ScenarioStep(stepName, action, null, null, waitStep, TimeoutSec: 15), "scenario_event", eventType, null, "waitStep: " + waitStep, "high")
                : null,
            "takeScreenshot" => new DraftStep(new ScenarioStep(stepName, action, null, null, null, Label: stepName), "scenario_event", eventType, null, action, "high"),
            "captureArtifacts" => new DraftStep(new ScenarioStep(stepName, action, null, null, null, Label: stepName), "scenario_event", eventType, null, action, "high"),
            _ => null
        };
    }

