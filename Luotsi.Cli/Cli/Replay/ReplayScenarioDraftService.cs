    public async Task<ReplayScenarioDraftResult> CreateAsync(CliOptions options, ArtifactSession artifacts)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentNullException.ThrowIfNull(artifacts);

        var output = options.Get("output") ?? options.Get("file");
        var validate = options.HasFlag("validate");
        if (validate && string.IsNullOrWhiteSpace(output))
        {
            throw new UsageException("replay scenario-draft --validate requires --output <scenario.json> or --file <scenario.json>.");
        }

        var events = ReadTimelineEvents(artifacts.Root);
        var normalizationNotes = new List<ReplayScenarioDraftNormalization>();
        var draftSteps = NormalizeSteps(CreateSteps(events), normalizationNotes);
        if (draftSteps.Count == 0)
        {
            throw new UsageException("replay scenario-draft could not find action events in session-timeline.jsonl.");
        }

        var steps = draftSteps.Select(static step => step.Step).ToArray();
        var warnings = BuildWarnings(steps).ToArray();
        var packageProvenance = InferPackageProvenance(events);
        var deviceProvenance = InferDeviceProvenance(artifacts.Root);
        var jsonPath = options.HasFlag("write-json")
            ? Path.Join(artifacts.Root, ScenarioDraftSummaryFileName)
            : null;
        var markdownPath = options.HasFlag("write-markdown")
            ? Path.Join(artifacts.Root, ScenarioDraftReviewFileName)
            : null;
        var scenario = new ScenarioFile(
            options.Get("name") ?? "draft from replay",
            steps,
            Tags: ["draft", "generated", "replay"],
            Metadata: new ScenarioMetadata(
                Package: packageProvenance?.Package,
                Notes: $"Generated by `luotsi replay scenario-draft` from artifact root {artifacts.Root}. Review selectors, waits, and coordinate-specific steps before committing.",
                Device: deviceProvenance is null ? null : new ScenarioDeviceMetadata(Serial: deviceProvenance.Serial)));
        var suggestions = BuildSuggestions(steps).ToArray();
        var origins = draftSteps
            .Select((step, index) => new ReplayScenarioDraftStepOrigin(
                index + 1,
                step.Source,
                step.EventType,
                step.Command,
                step.Detail,
                step.Confidence,
                step.SourcePath,
                step.Sequence,
                step.Timestamp,
                BuildSourceCommand(step.SourcePath, step.Sequence)))
            .ToArray();
        var sourceSummaries = BuildSourceSummaries(origins, normalizationNotes).ToArray();
        var reviewItems = BuildReviewItems(warnings, suggestions, origins, normalizationNotes).ToList();
        ReplayScenarioDraftValidation? validation = null;

        if (!string.IsNullOrWhiteSpace(output))
        {
            var directory = Path.GetDirectoryName(output);
            if (!string.IsNullOrWhiteSpace(directory))
            {
                _fileSystem.CreateDirectory(directory);
            }

            await _fileSystem.WriteAllTextAsync(output, JsonSerializer.Serialize(scenario, AppJson.Options) + Environment.NewLine, new UTF8Encoding(false)).ConfigureAwait(false);

            if (validate)
            {
                validation = await ValidateDraftAsync(output).ConfigureAwait(false);
            }
        }

        if (validation is { Status: "failed" } && !string.IsNullOrWhiteSpace(validation.Error))
        {
            reviewItems.Insert(0, new ReplayScenarioDraftReviewItem(
                "error",
                "validation",
                null,
                validation.Error,
                validation.Command));
        }

        var confidence = warnings.Length == 0 && !string.Equals(validation?.Status, "failed", StringComparison.OrdinalIgnoreCase)
            ? "medium"
            : "low";
        var runHandoff = BuildRunHandoff(output, validation, scenario);
        var nextActions = BuildNextActions(output, artifacts.Root, jsonPath, origins, reviewItems, normalizationNotes, validation, runHandoff).ToArray();
        var result = new ReplayScenarioDraftResult(
            ResultSchemas.ScenarioDraft,
            artifacts.Root,
            output,
            jsonPath,
            markdownPath,
            confidence,
            warnings,
            scenario,
            suggestions,
            reviewItems,
            sourceSummaries,
            origins,
            normalizationNotes,
            packageProvenance,
            deviceProvenance,
            validation,
            runHandoff,
            nextActions,
            BuildCommandHints(output, artifacts.Root, jsonPath, markdownPath, origins, validation, runHandoff).ToArray());

        if (jsonPath is not null)
        {
            await artifacts.WriteJsonAsync(ScenarioDraftSummaryFileName, result).ConfigureAwait(false);
        }

        if (markdownPath is not null)
        {
            await artifacts.WriteTextAsync(ScenarioDraftReviewFileName, BuildMarkdown(result)).ConfigureAwait(false);
        }

        return result;
    }

    private async Task<ReplayScenarioDraftValidation> ValidateDraftAsync(string output)
    {
        var command = BuildValidateCommand(output);
        try
        {
            _ = await _validationExecutorFactory.Create().ValidateFileAsync(output).ConfigureAwait(false);
            return new ReplayScenarioDraftValidation("validated", command, Message: "Static scenario validation passed.");
        }
        catch (Exception ex) when (ex is not OperationCanceledException)
        {
            return new ReplayScenarioDraftValidation("failed", command, Error: ex.Message);
        }
    }

    private static IReadOnlyList<DraftStep> NormalizeSteps(
        IReadOnlyList<DraftStep> steps,
        ICollection<ReplayScenarioDraftNormalization> normalizations)
    {
        var normalized = new List<DraftStep>();
        foreach (var step in steps)
        {
            if (TryCreateDuplicateWaitNormalization(normalized, step, out var normalization))
            {
                normalizations.Add(normalization);
                continue;
            }

            if (TryCreatePreTapWaitNormalization(normalized, step, out var waitStep, out normalization))
            {
                normalizations.Add(normalization);
                normalized.Add(waitStep);
            }

            normalized.Add(step);
        }

        return normalized;
    }

    private static bool TryCreateDuplicateWaitNormalization(
        IReadOnlyList<DraftStep> normalized,
        DraftStep candidate,
        out ReplayScenarioDraftNormalization normalization)
    {
        normalization = null!;
        var candidateKey = GetWaitKey(candidate.Step);
        if (candidateKey is null)
        {
            return false;
        }

        var previous = normalized.LastOrDefault();
        if (previous is null || !string.Equals(GetWaitKey(previous.Step), candidateKey, StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        normalization = new ReplayScenarioDraftNormalization(
            "duplicate_wait",
            $"Dropped adjacent duplicate {candidate.Step.Action} for `{GetStepTarget(candidate.Step)}`.",
            candidate.Source,
            candidate.EventType,
            candidate.Confidence,
            candidate.SourcePath,
            candidate.Sequence,
            candidate.Timestamp,
            BuildSourceCommand(candidate.SourcePath, candidate.Sequence));
        return true;
    }

    private static bool TryCreatePreTapWaitNormalization(
        IReadOnlyList<DraftStep> normalized,
        DraftStep candidate,
        out DraftStep waitStep,
        out ReplayScenarioDraftNormalization normalization)
    {
        waitStep = null!;
        normalization = null!;

        var wait = CreatePreTapWaitStep(candidate.Step);
        var waitKey = wait is null ? null : GetWaitKey(wait);
        if (wait is null || waitKey is null)
        {
            return false;
        }

        var previous = normalized.LastOrDefault();
        if (previous is not null && string.Equals(GetWaitKey(previous.Step), waitKey, StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        var target = GetStepTarget(candidate.Step);
        waitStep = candidate with
        {
            Step = wait,
            Detail = $"inserted {wait.Action} before {candidate.Step.Action}: {target}"
        };
        normalization = new ReplayScenarioDraftNormalization(
            "inserted_pre_tap_wait",
            $"Inserted {wait.Action} before {candidate.Step.Action} for `{target}`.",
            candidate.Source,
            candidate.EventType,
            candidate.Confidence,
            candidate.SourcePath,
            candidate.Sequence,
            candidate.Timestamp,
            BuildSourceCommand(candidate.SourcePath, candidate.Sequence));
        return true;
    }

    private static ScenarioStep? CreatePreTapWaitStep(ScenarioStep step) =>
        step.Action switch
        {
            "tapText" when !string.IsNullOrWhiteSpace(step.Text) =>
                new ScenarioStep("wait for " + step.Text, "waitVisible", step.Text, null, null, TimeoutSec: 15),
            "tapElement" when step.Selector is not null =>
                new ScenarioStep("wait for " + GetStepTarget(step), "waitElement", null, null, null, TimeoutSec: 15, Selector: step.Selector),
            _ => null
        };

    private static string? GetWaitKey(ScenarioStep step) =>
        step.Action switch
        {
            "waitVisible" when !string.IsNullOrWhiteSpace(step.Text) => "waitVisible:" + step.Text,
            "waitElement" when step.Selector is not null => "waitElement:" + step.Selector.Describe(),
            "waitStep" when !string.IsNullOrWhiteSpace(step.Step) => "waitStep:" + step.Step,
            "waitActionReady" when !string.IsNullOrWhiteSpace(step.Text) => "waitActionReady:" + step.Step + ":" + step.Text,
            "assertEvent" when !string.IsNullOrWhiteSpace(step.Event) => "assertEvent:" + step.Event,
            _ => null
        };

    private static string GetStepTarget(ScenarioStep step) =>
        step.Text ?? step.Selector?.Describe() ?? step.Step ?? step.Event ?? step.Code ?? step.Label ?? step.Action;

    private static IEnumerable<ReplayScenarioDraftSourceSummary> BuildSourceSummaries(
        IReadOnlyList<ReplayScenarioDraftStepOrigin> origins,
        IReadOnlyList<ReplayScenarioDraftNormalization> normalizations)
    {
        var sources = origins
            .Select(static origin => origin.Source)
            .Concat(normalizations.Select(static normalization => normalization.Source))
            .Distinct(StringComparer.OrdinalIgnoreCase)
            .OrderBy(static source => source, StringComparer.OrdinalIgnoreCase);

        foreach (var source in sources)
        {
            var sourceOrigins = origins
                .Where(origin => string.Equals(origin.Source, source, StringComparison.OrdinalIgnoreCase))
                .ToArray();
            var sourceNormalizations = normalizations.Count(normalization =>
                string.Equals(normalization.Source, source, StringComparison.OrdinalIgnoreCase));
            var eventTypes = sourceOrigins
                .Select(static origin => origin.EventType)
                .Concat(normalizations
                    .Where(normalization => string.Equals(normalization.Source, source, StringComparison.OrdinalIgnoreCase))
                    .Select(static normalization => normalization.EventType))
                .Where(static eventType => !string.IsNullOrWhiteSpace(eventType))
                .Distinct(StringComparer.OrdinalIgnoreCase)
                .OrderBy(static eventType => eventType, StringComparer.OrdinalIgnoreCase)
                .ToArray();

            yield return new ReplayScenarioDraftSourceSummary(
                source,
                sourceOrigins.Length,
                sourceNormalizations,
                eventTypes,
                SummarizeConfidence(sourceOrigins.Select(static origin => origin.Confidence)
                    .Concat(normalizations
                        .Where(normalization => string.Equals(normalization.Source, source, StringComparison.OrdinalIgnoreCase))
                        .Select(static normalization => normalization.Confidence))));
        }
    }

    private static string SummarizeConfidence(IEnumerable<string> confidenceValues)
    {
        var values = confidenceValues.ToArray();
        if (values.Any(static value => string.Equals(value, "low", StringComparison.OrdinalIgnoreCase)))
        {
            return "low";
        }

        if (values.Any(static value => string.Equals(value, "medium", StringComparison.OrdinalIgnoreCase)))
        {
            return "medium";
        }

        return values.Length == 0 ? "unknown" : "high";
    }

    private static string BuildMarkdown(ReplayScenarioDraftResult result)
    {
        var builder = new StringBuilder();
        builder.AppendLine("# Luotsi Scenario Draft");
        builder.AppendLine();
        builder.AppendLine($"Artifact root: `{result.ArtifactRoot}`");
        builder.AppendLine($"Scenario: `{result.Scenario.Name}`");
        builder.AppendLine($"Output: `{result.Output ?? "(not written)"}`");
        builder.AppendLine($"Confidence: `{result.Confidence}`");
        builder.AppendLine($"Steps: `{result.Scenario.Steps.Count}`");
        if (result.Validation is not null)
        {
            builder.AppendLine();
            builder.AppendLine("## Validation");
            builder.AppendLine();
            builder.AppendLine($"- Status: `{EscapeMarkdown(result.Validation.Status)}`");
            builder.AppendLine($"- Command: `{EscapeMarkdown(result.Validation.Command)}`");
            if (!string.IsNullOrWhiteSpace(result.Validation.Message))
            {
                builder.AppendLine($"- Message: {EscapeMarkdown(result.Validation.Message)}");
            }

            if (!string.IsNullOrWhiteSpace(result.Validation.Error))
            {
                builder.AppendLine($"- Error: {EscapeMarkdown(result.Validation.Error)}");
            }
        }

        if (result.PackageProvenance is not null)
        {
            builder.AppendLine();
            builder.AppendLine("## Package Provenance");
            builder.AppendLine();
            builder.AppendLine($"- Package: `{EscapeMarkdown(result.PackageProvenance.Package)}`");
            builder.AppendLine($"- Source: `{EscapeMarkdown(result.PackageProvenance.Source)}`");
            builder.AppendLine($"- Event: `{EscapeMarkdown(result.PackageProvenance.EventType)}`");
            if (!string.IsNullOrWhiteSpace(result.PackageProvenance.Command))
            {
                builder.AppendLine($"- Command: `{EscapeMarkdown(result.PackageProvenance.Command)}`");
            }

            if (!string.IsNullOrWhiteSpace(result.PackageProvenance.SourcePath) && result.PackageProvenance.Sequence is { } sequence)
            {
                builder.AppendLine($"- Timeline: `{EscapeMarkdown(result.PackageProvenance.SourcePath)}:{sequence}`");
            }

            if (!string.IsNullOrWhiteSpace(result.PackageProvenance.SourceCommand))
            {
                builder.AppendLine($"- Reopen: `{EscapeMarkdown(result.PackageProvenance.SourceCommand)}`");
            }
        }

        if (result.DeviceProvenance is not null)
        {
            builder.AppendLine();
            builder.AppendLine("## Device Provenance");
            builder.AppendLine();
            builder.AppendLine($"- Serial: `{EscapeMarkdown(result.DeviceProvenance.Serial)}`");
            builder.AppendLine($"- Source: `{EscapeMarkdown(result.DeviceProvenance.Source)}`");
            builder.AppendLine($"- Session: `{EscapeMarkdown(result.DeviceProvenance.SessionKind)}`");
            if (!string.IsNullOrWhiteSpace(result.DeviceProvenance.SessionId))
            {
                builder.AppendLine($"- Session id: `{EscapeMarkdown(result.DeviceProvenance.SessionId)}`");
            }

            if (!string.IsNullOrWhiteSpace(result.DeviceProvenance.SourcePath))
            {
                builder.AppendLine($"- Metadata: `{EscapeMarkdown(result.DeviceProvenance.SourcePath)}`");
            }
        }

        if (result.RunHandoff is not null)
        {
            builder.AppendLine();
            builder.AppendLine("## Run Handoff");
            builder.AppendLine();
            builder.AppendLine($"- Status: `{EscapeMarkdown(result.RunHandoff.Status)}`");
            builder.AppendLine($"- Reason: {EscapeMarkdown(result.RunHandoff.Reason)}");
            if (!string.IsNullOrWhiteSpace(result.RunHandoff.DryRunCommand))
            {
                builder.AppendLine($"- Dry run: `{EscapeMarkdown(result.RunHandoff.DryRunCommand)}`");
            }

            if (!string.IsNullOrWhiteSpace(result.RunHandoff.PreflightCommand))
            {
                builder.AppendLine($"- Preflight: `{EscapeMarkdown(result.RunHandoff.PreflightCommand)}`");
            }

            if (!string.IsNullOrWhiteSpace(result.RunHandoff.ClaimedRunCommand))
            {
                builder.AppendLine($"- Claimed run: `{EscapeMarkdown(result.RunHandoff.ClaimedRunCommand)}`");
            }

            if (!string.IsNullOrWhiteSpace(result.RunHandoff.RunCommand))
            {
                builder.AppendLine($"- Run: `{EscapeMarkdown(result.RunHandoff.RunCommand)}`");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Warnings");
        builder.AppendLine();
        if (result.Warnings.Count == 0)
        {
            builder.AppendLine("- None");
        }
        else
        {
            foreach (var warning in result.Warnings)
            {
                builder.AppendLine("- " + warning);
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Suggestions");
        builder.AppendLine();
        if (result.Suggestions.Count == 0)
        {
            builder.AppendLine("- None");
        }
        else
        {
            foreach (var suggestion in result.Suggestions)
            {
                builder.AppendLine($"- Step {suggestion.StepIndex}: `{suggestion.Kind}` ({suggestion.Confidence}) - {suggestion.Message}");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Review Checklist");
        builder.AppendLine();
        if (result.ReviewItems.Count == 0)
        {
            builder.AppendLine("- None");
        }
        else
        {
            foreach (var item in result.ReviewItems)
            {
                var step = item.StepIndex is null ? string.Empty : $" step {item.StepIndex}:";
                var command = string.IsNullOrWhiteSpace(item.Command) ? string.Empty : $" `{item.Command}`";
                builder.AppendLine($"- `{item.Severity}` `{item.Category}`{step} {item.Message}{command}");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Recommended Next Actions");
        builder.AppendLine();
        if (result.NextActions.Count == 0)
        {
            builder.AppendLine("- None");
        }
        else
        {
            foreach (var action in result.NextActions)
            {
                builder.AppendLine($"- `{action.Kind}` {action.Title}: {action.Reason} `{action.Command}`");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Next Commands");
        builder.AppendLine();
        foreach (var command in result.SuggestedCommands)
        {
            builder.AppendLine($"- `{command.Command}`");
            builder.AppendLine($"  {command.Purpose}");
        }

        builder.AppendLine();
        builder.AppendLine("## Source Summary");
        builder.AppendLine();
        builder.AppendLine("| Source | Steps | Normalizations | Events | Confidence |");
        builder.AppendLine("|---|---:|---:|---|---|");
        foreach (var summary in result.SourceSummaries)
        {
            builder.Append("| ");
            builder.Append(EscapeMarkdown(summary.Source));
            builder.Append(" | ");
            builder.Append(summary.StepCount);
            builder.Append(" | ");
            builder.Append(summary.NormalizationCount);
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(string.Join(", ", summary.EventTypes)));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(summary.Confidence));
            builder.AppendLine(" |");
        }

        builder.AppendLine();
        builder.AppendLine("## Normalizations");
        builder.AppendLine();
        if (result.Normalizations.Count == 0)
        {
            builder.AppendLine("- None");
        }
        else
        {
            foreach (var normalization in result.Normalizations)
            {
                var location = string.IsNullOrWhiteSpace(normalization.SourcePath)
                    ? string.Empty
                    : $" at `{normalization.SourcePath}:{normalization.Sequence}`";
                builder.AppendLine($"- `{normalization.Kind}` ({normalization.Confidence}) from `{normalization.Source}`{location}: {normalization.Detail}");
            }
        }

        builder.AppendLine();
        builder.AppendLine("## Step Origins");
        builder.AppendLine();
        builder.AppendLine("| # | Source | File | Seq | Event | Command | Confidence | Detail | Reopen |");
        builder.AppendLine("|---:|---|---|---:|---|---|---|---|---|");
        foreach (var origin in result.StepOrigins)
        {
            builder.Append("| ");
            builder.Append(origin.StepIndex);
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(origin.Source));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(origin.SourcePath ?? string.Empty));
            builder.Append(" | ");
            builder.Append(origin.Sequence?.ToString(System.Globalization.CultureInfo.InvariantCulture) ?? string.Empty);
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(origin.EventType));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(origin.Command ?? string.Empty));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(origin.Confidence));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(origin.Detail ?? string.Empty));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(origin.SourceCommand ?? string.Empty));
            builder.AppendLine(" |");
        }

        builder.AppendLine();
        builder.AppendLine("## Draft Steps");
        builder.AppendLine();
        builder.AppendLine("| # | Action | Name | Text/Code/Label |");
        builder.AppendLine("|---:|---|---|---|");
        for (var i = 0; i < result.Scenario.Steps.Count; i++)
        {
            var step = result.Scenario.Steps[i];
            builder.Append("| ");
            builder.Append(i + 1);
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(step.Action));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(step.Name ?? string.Empty));
            builder.Append(" | ");
            builder.Append(EscapeMarkdown(GetStepTarget(step)));
            builder.AppendLine(" |");
        }

        return builder.ToString();
    }

    private static IEnumerable<ReplayScenarioDraftNextAction> BuildNextActions(
        string? output,
        string artifactRoot,
        string? jsonPath,
        IReadOnlyList<ReplayScenarioDraftStepOrigin> origins,
        IReadOnlyList<ReplayScenarioDraftReviewItem> reviewItems,
        IReadOnlyList<ReplayScenarioDraftNormalization> normalizations,
        ReplayScenarioDraftValidation? validation,
        ReplayScenarioDraftRunHandoff? runHandoff)
    {
        var reviewReason = reviewItems.Count == 0 && normalizations.Count == 0
            ? "Confirm the generated scenario flow and source provenance before editing."
            : $"Review {reviewItems.Count} checklist item(s) and {normalizations.Count} normalization(s) before editing.";
        yield return new ReplayScenarioDraftNextAction(
            "review_draft",
            "Review generated draft",
            reviewReason,
            $"luotsi replay open --artifacts {Quote(artifactRoot)}");

        var validationPassed = string.Equals(validation?.Status, "validated", StringComparison.OrdinalIgnoreCase);
        if (!string.IsNullOrWhiteSpace(output) && !validationPassed)
        {
            var reason = string.Equals(validation?.Status, "failed", StringComparison.OrdinalIgnoreCase)
                ? "Resolve the static validation failure before committing or running the draft."
                : "Run static scenario validation before committing or running the draft.";
            yield return new ReplayScenarioDraftNextAction(
                "validate_scenario",
                "Validate generated scenario",
                reason,
                BuildValidateCommand(output));
        }

        if (validationPassed && !string.IsNullOrWhiteSpace(output))
        {
            yield return new ReplayScenarioDraftNextAction(
                "dry_run_scenario",
                "Plan scenario run",
                "Confirm the generated scenario is selected as expected before starting a device run.",
                BuildDryRunCommand(output));

            if (!string.IsNullOrWhiteSpace(runHandoff?.PreflightCommand))
            {
                yield return new ReplayScenarioDraftNextAction(
                    "preflight_device",
                    "Preflight target device",
                    "Verify adb/device/app readiness before executing the generated scenario.",
                    runHandoff.PreflightCommand);
            }
        }

        if (!string.IsNullOrWhiteSpace(jsonPath))
        {
            yield return new ReplayScenarioDraftNextAction(
                "audit_provenance",
                "Audit draft provenance",
                "Use the graph to inspect generated steps, draft normalizations, source families, and timeline links.",
                $"luotsi replay graph --artifacts {Quote(artifactRoot)} --node-kind scenario_draft --write-markdown");
        }

        var firstOrigin = origins.FirstOrDefault(static origin => !string.IsNullOrWhiteSpace(origin.SourceCommand));
        if (!string.IsNullOrWhiteSpace(firstOrigin?.SourceCommand))
        {
            yield return new ReplayScenarioDraftNextAction(
                "reopen_source_event",
                "Reopen first source event",
                "Inspect the timeline event that produced the first generated draft step.",
                firstOrigin.SourceCommand);
        }
    }

    private static IEnumerable<ReplayScenarioDraftCommandHint> BuildCommandHints(
        string? output,
        string artifactRoot,
        string? jsonPath,
        string? markdownPath,
        IReadOnlyList<ReplayScenarioDraftStepOrigin> origins,
        ReplayScenarioDraftValidation? validation,
        ReplayScenarioDraftRunHandoff? runHandoff)
    {
        yield return new ReplayScenarioDraftCommandHint(
            $"luotsi replay packet --artifacts {Quote(artifactRoot)}",
            "Write the durable first-minute packet before editing or sharing the generated draft.");

        yield return new ReplayScenarioDraftCommandHint(
            $"luotsi replay packet --artifacts {Quote(artifactRoot)} --check",
            "Validate the durable packet before handoff or deeper replay.");

        yield return new ReplayScenarioDraftCommandHint(
            $"luotsi replay open --artifacts {Quote(artifactRoot)}",
            "Open the artifact browser for screenshots, timelines, and generated draft review files.");

        yield return new ReplayScenarioDraftCommandHint(
            $"luotsi replay capsule --artifacts {Quote(artifactRoot)} --write-readme --write-json",
            "Write the replay capsule that links the draft to failures, artifacts, and follow-up commands.");

        yield return new ReplayScenarioDraftCommandHint(
            $"luotsi replay scrub --artifacts {Quote(artifactRoot)} --context 3 --write-markdown",
            "Write a scrub view around the same evidence before editing the draft.");

        if (!string.IsNullOrWhiteSpace(jsonPath))
        {
            yield return new ReplayScenarioDraftCommandHint(
                $"luotsi replay graph --artifacts {Quote(artifactRoot)} --node-kind scenario_draft --write-markdown",
                "Audit draft provenance, generated steps, and normalizations in the semantic graph.");
        }

        var validationPassed = string.Equals(validation?.Status, "validated", StringComparison.OrdinalIgnoreCase);
        if (!string.IsNullOrWhiteSpace(output) && !validationPassed)
        {
            yield return new ReplayScenarioDraftCommandHint(
                BuildValidateCommand(output),
                "Validate the generated scenario before committing or running it.");
        }

        if (runHandoff is not null &&
            string.Equals(runHandoff.Status, "ready", StringComparison.OrdinalIgnoreCase) &&
            !string.IsNullOrWhiteSpace(runHandoff.PreflightCommand) &&
            !string.IsNullOrWhiteSpace(runHandoff.DryRunCommand) &&
            !string.IsNullOrWhiteSpace(runHandoff.RunCommand))
        {
            yield return new ReplayScenarioDraftCommandHint(
                runHandoff.DryRunCommand,
                "Plan the generated scenario without starting a device run.");

            yield return new ReplayScenarioDraftCommandHint(
                runHandoff.PreflightCommand,
                "Check the selected device and target app before executing the generated scenario.");

            if (!string.IsNullOrWhiteSpace(runHandoff.ClaimedRunCommand))
            {
                yield return new ReplayScenarioDraftCommandHint(
                    runHandoff.ClaimedRunCommand,
                    "Claim the selected device before running the generated scenario in a shared lab.");
            }

            yield return new ReplayScenarioDraftCommandHint(
                runHandoff.RunCommand,
                "Run the generated scenario on a selected device after review.");
        }

        if (!string.IsNullOrWhiteSpace(markdownPath))
        {
            yield return new ReplayScenarioDraftCommandHint(
                $"luotsi replay search --artifacts {Quote(artifactRoot)} --contains \"Review Checklist\"",
                "Find the generated review checklist in replay artifacts.");
        }

        var firstOrigin = origins.FirstOrDefault(static origin => !string.IsNullOrWhiteSpace(origin.SourceCommand));
        if (!string.IsNullOrWhiteSpace(firstOrigin?.SourceCommand))
        {
            yield return new ReplayScenarioDraftCommandHint(
                firstOrigin.SourceCommand,
                "Reopen the first generated step's source timeline event.");
        }
    }

